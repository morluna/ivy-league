import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const fields={'session':{value:'https://rally.example/?s=test-session'},'owner-key':{value:'test-owner-key-with-at-least-32-characters'}};
const button={disabled:false};
const form={elements:{namedItem:k=>fields[k]},querySelector:()=>button};
const message={textContent:''}, link={hidden:true};
let calls=[];
const context=vm.createContext({URL,AbortSignal,window:{confirm:()=>false},document:{getElementById:id=>({'owner-end':form,'owner-message':message,'session-link':link})[id]},fetch:async(path,options)=>{calls.push({path,options});return {ok:true,json:async()=>({session:{status:'closed'}})};}});
vm.runInContext(await readFile(new URL('../static/admin.js',import.meta.url),'utf8'),context);
await form.onsubmit({preventDefault(){}});
assert.equal(calls.length,0);
context.window.confirm=()=>true;
await form.onsubmit({preventDefault(){}});
assert.equal(calls[0].path,'/api/admin/sessions/test-session/end');
assert.equal(calls[0].options.headers.Authorization,'Bearer test-owner-key-with-at-least-32-characters');
assert.equal(calls[0].options.body,'{}');
assert.equal(fields['owner-key'].value,'');
assert.equal(link.href,'/?s=test-session');
assert.equal(link.hidden,false);
assert.equal(button.disabled,false);
console.log('PASS: owner end-session confirmation, header-only credential, and cleared password.');
